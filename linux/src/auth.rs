fn dword(w: &[u8]) -> u32 { (u32::from(w[0]) << 16) | (u32::from(w[1]) << 24) | u32::from(w[2]) | (u32::from(w[3]) << 8) }
fn decode(resp: &[u8]) -> Result<Vec<u8>, Error> {
    if resp.len() != 512 { return Err(Error::ShortTransfer { expected: 512, actual: resp.len() }); }
    let count = dword(&resp[8..12]);
    if count > 60 { return Err(Error::ProtocolUnavailable("secure response parameter count out of range")); }
    let mut out = vec![0; 256];
    out[..4].copy_from_slice(&dword(&resp[4..8]).to_le_bytes());
    for i in 0..count as usize { out[4+i*4..8+i*4].copy_from_slice(&dword(&resp[16+i*4..20+i*4]).to_le_bytes()); }
    Ok(out)
}

pub fn authenticate<T: Transport>(t: &mut T) -> Result<[u8; 16], Error> {
    t.reg_write(0x90078, &[8, 4])?;
    let input = build_secure_command(0x01010000, 8, &DRIVER_VERSION);
    let response = send(t, 0x01010000, &input, None)?;
    let decoded = decode(&response)?;
    if decoded.len() < 40 { return Err(Error::ProtocolUnavailable("certificate response is truncated")); }
    let secure_version = decoded[0x27];
    let mut h = MAGIC.to_vec(); h.push(secure_version); h.push(0x0b);
    let index = (sha1_bytes(&[&h])[19] & 0x0f) as usize;
    let challenge = [swap_dwords(&decoded[4..36])?, swap_dwords(&PASSWORDS[index])?].concat();
    let challenge_hash = sha1_bytes(&[&challenge]);
    let response_cmd = build_secure_command(0x01020000, 5, &challenge_hash);
    let _ = send(t, 0x01020000, &response_cmd, None)?;
    let digest = sha1_bytes(&[&challenge_hash, &swap_dwords(&PASSWORDS[index])?]);
    Ok([digest[16],digest[17],digest[18],digest[19],digest[6],digest[7],digest[8],digest[9],digest[11],digest[12],digest[13],digest[14],digest[0],digest[1],digest[2],digest[3]])
}

pub fn send<T: Transport>(t: &mut T, id: u32, input: &[u8; 512], key: Option<&[u8; 16]>) -> Result<Vec<u8>, Error> {
    let mut wire = *input;
    if id & 0x400 != 0 {
        let key = key.ok_or(Error::ProtocolUnavailable("encrypted secure command without key"))?;
        let encrypted = aes_cbc(key, &wire[12..508], false)?;
        for (dst, src) in wire[12..508].chunks_exact_mut(2).zip(encrypted.chunks_exact(2)) { dst[0] = src[1]; dst[1] = src[0]; }
        swap_words(&mut wire, 510)?;
    } else { swap_words(&mut wire, 12)?; }
    t.reg_write(SECURE_REG, &wire)?;
    t.api_command(&[0,0,8,0,0,0])?;
    let mut acked = false;
    for _ in 0..20 { if !t.ack(Duration::from_millis(500))?.is_empty() { acked = true; break; } }
    if !acked { return Err(Error::ProtocolUnavailable("secure command ACK not received")); }
    let mut response = t.reg_read(SECURE_REG, 512)?;
    swap_words(&mut response, 510)?;
    if response.len() < 12 { return Err(Error::ProtocolUnavailable("secure response truncated")); }
    if id & 0x400 != 0 {
        let key = key.ok_or(Error::ProtocolUnavailable("encrypted secure response without key"))?;
        let mut cipher = response[12..508].to_vec(); swap_words(&mut cipher, cipher.len())?;
        let plain = aes_cbc(key, &cipher, true)?; response[12..508].copy_from_slice(&plain);
    }
    Ok(response)
}

